create or replace function public.app_get_narrator_musnad(
  p_narration_count integer default 1,
  p_volume_ids bigint[] default null,
  p_book_ids bigint[] default null,
  p_chapter_ids bigint[] default null,
  p_limit integer default 200,
  p_offset integer default 0
)
returns table (
  rawi_id bigint,
  rawi_name text,
  narration_count bigint,
  hadith_id bigint,
  hadith_number text,
  hadith_text text,
  hadith_type text,
  chapter_name text,
  book_name text,
  volume_name text
)
language sql
stable
security definer
set search_path = public
as $$
  with filtered as (
    select hr.rawi_id, count(distinct hr.hadith_id) as narration_count
    from public.hadith_rawi hr
    join public.hadith h on h.id = hr.hadith_id
    join public.chapters c on c.id = h.chapter_id
    join public.books b on b.id = c.book_id
    join public.volumes v on v.id = b.volume_id
    where (p_volume_ids is null or cardinality(p_volume_ids) = 0 or v.id = any(p_volume_ids))
      and (p_book_ids is null or cardinality(p_book_ids) = 0 or b.id = any(p_book_ids))
      and (p_chapter_ids is null or cardinality(p_chapter_ids) = 0 or c.id = any(p_chapter_ids))
    group by hr.rawi_id
    having count(distinct hr.hadith_id) = coalesce(p_narration_count, 1)
  )
  select
    r.id,
    r.name,
    f.narration_count,
    h.id,
    h.hadith_number,
    h.text,
    h.type,
    c.name,
    b.name,
    v.name
  from filtered f
  join public.rawis r on r.id = f.rawi_id
  join public.hadith_rawi hr on hr.rawi_id = r.id
  join public.hadith h on h.id = hr.hadith_id
  join public.chapters c on c.id = h.chapter_id
  join public.books b on b.id = c.book_id
  join public.volumes v on v.id = b.volume_id
  where (p_volume_ids is null or cardinality(p_volume_ids) = 0 or v.id = any(p_volume_ids))
    and (p_book_ids is null or cardinality(p_book_ids) = 0 or b.id = any(p_book_ids))
    and (p_chapter_ids is null or cardinality(p_chapter_ids) = 0 or c.id = any(p_chapter_ids))
  order by f.narration_count desc, r.name, v.order_index, b.order_index, c.order_index, h.order_index
  limit greatest(1, least(coalesce(p_limit, 200), 1000))
  offset greatest(0, coalesce(p_offset, 0));
$$;


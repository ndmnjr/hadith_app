create or replace function public.app_get_filter_tree()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'volumes', coalesce((
      select jsonb_agg(jsonb_build_object('id', v.id, 'name', v.name, 'order_index', v.order_index) order by v.order_index, v.id)
      from public.volumes v
    ), '[]'::jsonb),
    'books', coalesce((
      select jsonb_agg(jsonb_build_object('id', b.id, 'volume_id', b.volume_id, 'name', b.name, 'order_index', b.order_index) order by b.order_index, b.id)
      from public.books b
    ), '[]'::jsonb),
    'chapters', coalesce((
      select jsonb_agg(jsonb_build_object('id', c.id, 'book_id', c.book_id, 'name', c.name, 'order_index', c.order_index) order by c.order_index, c.id)
      from public.chapters c
    ), '[]'::jsonb)
  );
$$;

create or replace function public.app_search_hadith(
  p_query text default null,
  p_volume_ids bigint[] default null,
  p_book_ids bigint[] default null,
  p_chapter_ids bigint[] default null,
  p_types text[] default null,
  p_limit integer default 50,
  p_offset integer default 0
)
returns table (
  hadith_id bigint,
  hadith_number text,
  hadith_text text,
  text_html text,
  hadith_type text,
  page_number integer,
  takhreej text,
  takhreej_full text,
  chapter_id bigint,
  chapter_name text,
  book_id bigint,
  book_name text,
  volume_id bigint,
  volume_name text,
  volume_order integer,
  book_order integer,
  chapter_order integer,
  hadith_order integer,
  narrators text
)
language sql
stable
security definer
set search_path = public
as $$
  select
    h.id,
    h.hadith_number,
    h.text,
    h.text_html,
    h.type,
    h.page_number,
    h.takhreej,
    h.takhreej_full,
    c.id,
    c.name,
    b.id,
    b.name,
    v.id,
    v.name,
    v.order_index,
    b.order_index,
    c.order_index,
    h.order_index,
    coalesce(string_agg(distinct r.name, '، ' order by r.name), '') as narrators
  from public.hadith h
  join public.chapters c on c.id = h.chapter_id
  join public.books b on b.id = c.book_id
  join public.volumes v on v.id = b.volume_id
  left join public.hadith_rawi hr on hr.hadith_id = h.id
  left join public.rawis r on r.id = hr.rawi_id
  where (p_query is null or btrim(p_query) = '' or public.normalize_ar(h.text) ilike '%' || public.normalize_ar(p_query) || '%')
    and (p_volume_ids is null or cardinality(p_volume_ids) = 0 or v.id = any(p_volume_ids))
    and (p_book_ids is null or cardinality(p_book_ids) = 0 or b.id = any(p_book_ids))
    and (p_chapter_ids is null or cardinality(p_chapter_ids) = 0 or c.id = any(p_chapter_ids))
    and (p_types is null or cardinality(p_types) = 0 or h.type = any(p_types))
  group by h.id, c.id, b.id, v.id
  order by v.order_index, b.order_index, c.order_index, h.order_index, h.id
  limit greatest(1, least(coalesce(p_limit, 50), 500))
  offset greatest(0, coalesce(p_offset, 0));
$$;

create or replace function public.app_get_hadith_index(
  p_volume_ids bigint[] default null,
  p_book_ids bigint[] default null,
  p_chapter_ids bigint[] default null,
  p_limit integer default 100,
  p_offset integer default 0
)
returns table (
  hadith_id bigint,
  hadith_number text,
  hadith_beginning text,
  hadith_type text,
  chapter_name text,
  book_name text,
  volume_name text,
  hadith_order integer
)
language sql
stable
security definer
set search_path = public
as $$
  select
    h.id,
    h.hadith_number,
    array_to_string((regexp_split_to_array(btrim(h.text), '\s+'))[1:15], ' ')
      || case when array_length(regexp_split_to_array(btrim(h.text), '\s+'), 1) > 15 then '...' else '' end,
    h.type,
    c.name,
    b.name,
    v.name,
    h.order_index
  from public.hadith h
  join public.chapters c on c.id = h.chapter_id
  join public.books b on b.id = c.book_id
  join public.volumes v on v.id = b.volume_id
  where h.type in ('main', 'sub', 'part', 'h_main', 'h_part')
    and (p_volume_ids is null or cardinality(p_volume_ids) = 0 or v.id = any(p_volume_ids))
    and (p_book_ids is null or cardinality(p_book_ids) = 0 or b.id = any(p_book_ids))
    and (p_chapter_ids is null or cardinality(p_chapter_ids) = 0 or c.id = any(p_chapter_ids))
  order by v.order_index, b.order_index, c.order_index, h.order_index, h.id
  limit greatest(1, least(coalesce(p_limit, 100), 1000))
  offset greatest(0, coalesce(p_offset, 0));
$$;

create or replace function public.app_search_rawis(
  p_query text default null,
  p_limit integer default 20
)
returns table (
  rawi_id bigint,
  rawi_name text,
  matched_alias text,
  match_source text
)
language sql
stable
security definer
set search_path = public
as $$
  with matches as (
    select r.id as rawi_id, r.name as rawi_name, null::text as matched_alias, 'name'::text as match_source
    from public.rawis r
    where p_query is null or btrim(p_query) = '' or public.normalize_ar(r.name) ilike '%' || public.normalize_ar(p_query) || '%'
    union
    select r.id, r.name, a.alias, coalesce(a.alias_type, 'alias')
    from public.rawis r
    join public.rawi_aliases a on a.rawi_id = r.id
    where p_query is not null and btrim(p_query) <> ''
      and public.normalize_ar(a.alias) ilike '%' || public.normalize_ar(p_query) || '%'
  )
  select distinct on (rawi_id, coalesce(matched_alias, '')) rawi_id, rawi_name, matched_alias, match_source
  from matches
  order by rawi_id, coalesce(matched_alias, ''), rawi_name
  limit greatest(1, least(coalesce(p_limit, 20), 100));
$$;

